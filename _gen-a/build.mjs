const shell = (title, css, header, body) => `<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${title}</title>
<style>
  html,body{margin:0;height:100%;background:#04060a;overflow:hidden}
  #c{position:fixed;inset:0;width:100%;height:100%;display:block}
  #vig{position:fixed;inset:0;pointer-events:none;z-index:2;
       background:radial-gradient(132% 108% at 50% 48%,transparent 38%,rgba(2,4,8,.50) 74%,rgba(1,2,5,.92))}
  #hint{position:fixed;left:50%;bottom:14px;transform:translateX(-50%);z-index:3;
        font:500 11px/1.5 ui-monospace,Consolas,monospace;
        color:rgba(150,205,220,.32);letter-spacing:.10em;pointer-events:none;transition:opacity .6s}
${css}
</style>
</head>
<body data-chrome="off">
<canvas id="c"></canvas>
<div id="vig"></div>
<div id="hint">等待第一句…</div>
<script>
"use strict";
${header}
${body}
</script>
</body>
</html>
`;

const core = fs.readFileSync(GEN + '/core.js', 'utf8');
const only = process.argv.slice(2);
for (const m of MANIFEST) {
  if (only.length && !only.includes(m.no)) continue;
  const mechPath = GEN + '/' + m.mech;
  if (!fs.existsSync(mechPath)) { console.log('skip (no mech):', m.no); continue; }
  const mech = fs.readFileSync(mechPath, 'utf8');
  const header = `/* ============================================================================\n   ${m.head}\n   ========================================================================== */\n`;
  const boot = `\n/* ---- 启动（必须在所有机制代码之后） ---- */\nmechInit();\nresize();\nrequestAnimationFrame(frame);\n`;
  const html = shell(m.title, m.css, header, core + '\n\n/* ================= 机制 ================= */\n' + mech + boot);
  const out = `${OUT}/${m.no}-${m.name}.html`;
  fs.writeFileSync(out, html, 'utf8');
  console.log('built', path.basename(out), (html.length / 1024).toFixed(1) + 'KB');
}
